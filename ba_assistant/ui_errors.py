def error_message(error: Exception) -> str:
    detail = {
        "http_error": "Сервіс відхилив запит: перевірте ключ і квоту безплатних запитів.",
        "provider_error": "Модель зараз недоступна або квоту вичерпано.",
        "timeout": "Модель не відповіла вчасно. Можна повторити спробу.",
        "generation_timeout": "Модель не завершила документи за 3 хвилини. Підтверджені вимоги збережено. Це може бути затримка сервісу; не починайте діалог заново.",
        "network_error": "Немає зв’язку із сервісом. Можна повторити спробу.",
        "invalid_output": "Відповідь моделі не відповідає формату. Стан не підтверджено.",
        "output_truncated": "Модель не завершила відповідь у межах дозволеного обсягу. Код: output_truncated.",
        "output_refused": "Модель відмовилась відповідати або спрацював фільтр сервісу. Код: output_refused.",
        "output_empty": "Модель повернула порожню відповідь. Код: output_empty.",
        "output_not_json": "Модель повернула некоректний JSON замість структурованої відповіді. Код: output_not_json.",
        "output_schema": "JSON отримано, але його поля не відповідають формату застосунку. Наступна спроба передасть моделі вказівку виправити формат. Код: output_schema.",
        "validation_error": "Відповідь моделі не пройшла перевірку. Попередні факти збережено; повторіть аналіз останнього повідомлення.",
        "invalid_evidence": "Модель навела цитату, якої немає у відповідному повідомленні. Попередні факти збережено; повторіть аналіз.",
        "unknown_fact_target": "Модель намагається змінити невідомий факт. Попередні факти збережено; повторіть аналіз.",
        "invalid_fact_revision": "Модель неправильно змінила категорію або відхилений факт. Повторіть аналіз.",
        "unknown_issue_fact": "Питання моделі посилається на невідомий факт. Повторіть аналіз.",
        "duplicate_fact_targets": "Модель запропонувала кілька змін одного факту за раз. Повторіть аналіз.",
    }.get(str(error), "Перевірте факти й відкриті питання або повторіть спробу.")
    status = getattr(error, "status", None)
    diagnostic = getattr(error, "diagnostic", None)
    if str(error) == "output_schema" and diagnostic:
        detail += " Поля: " + diagnostic
    if str(error) in {"http_error", "provider_error"} and status is not None:
        detail = {
            400: "Сервіс не прийняв параметри запиту. Потрібна перевірка сумісності моделі й формату відповіді.",
            401: "Сервіс не прийняв ключ. Перевірте його чинність і підключіть знову.",
            402: "Запит заблоковано обмеженням кредитів або облікового запису. Не поповнюйте баланс для діагностики: застосунок налаштовано лише на безплатні запити.",
            403: "Доступ заборонено. Причиною можуть бути дозволи ключа, політики доступу або обмеження облікового запису.",
            404: "Модель або сумісний маршрут недоступні. Потрібно перевірити підтримку параметрів і налаштування приватності OpenRouter.",
            422: "Сервіс не прийняв формат запиту. Потрібна перевірка параметрів і JSON-схеми.",
            429: "Перевищено ліміт запитів або безплатна модель перевантажена. Спробуйте пізніше.",
        }.get(status, "Помилка сервісу моделі. Спробуйте пізніше." if status >= 500 else detail)
        detail = f"Код {status}. {detail}"
    return "Дію не завершено. " + detail
